#!/usr/bin/env python3
"""Record the two remaining mandatory-method runs once their logs exist.

Refuses to write unless the full official RefCOCO val population is present.
"""
import json, os, re, sys, datetime

ROOT = '/home/msj_team/Jacob/research/ris'
DEEP = os.path.join(ROOT, 'exp/out_final/deep_read.json')
TAS_LOG = '/home/msj_team/Jacob/sys/tas_run/tas_val_main2.log'
T4S_JSON = os.path.join(ROOT, 'exp/out_final/text4seg_refcoco_val.json')
TAS_EVID = os.path.join(ROOT, 'exp/out_final/tas_refcoco_val.json')
T4S_EVID = T4S_JSON
SPLITS_OTHER = ['refcoco_testA', 'refcoco_testB', 'refcocoplus_val', 'refcocoplus_testA',
                'refcocoplus_testB', 'refcocog_val', 'refcocog_testu', 'grefcoco_val']


def blockers(ev):
    return {s: {'reason': 'Official split not evaluated in this pass; the full RefCOCO val split was run end-to-end.',
                'evidence': ev} for s in SPLITS_OTHER}


def parse_tas():
    s = open(TAS_LOG, errors='ignore').read()
    if 'TAS_EXIT=0' not in s or 'TAS_MAIN2_DONE' not in s:
        raise SystemExit('TAS not finished successfully')
    def num(pat):
        m = re.search(pat, s)
        if not m:
            raise SystemExit('missing TAS metric ' + pat)
        return float(m.group(1).rstrip('.'))
    miou = num(r'mIoU=([\d.]+)')
    oiou = num(r'oIoU=([\d.]+)')
    prec = {}
    for k in [50, 60, 70, 80, 90]:
        m = re.search(rf'Pr@{k}: ([\d.]+)', s)
        if m:
            prec[f'Pr@{k}'] = float(m.group(1).rstrip('.'))
    out = {'method': 'TAS (official zero-shot pipeline)', 'kind': 'method', 'full_split': True,
           'split': 'refcoco_val', 'n': 10834,
           'protocol': ('Official TAS test.py path on the full RefCOCO val split (3,811 refs / 10,834 expressions): '
                        'SAM ViT-H automatic masks, BLIP-2 OPT-2.7B captions, CLIP ViT-B/32 scoring plus spaCy/heuristic '
                        'spatial rectification. mIoU = mean per-expression IoU; oIoU = pooled intersection/union; Pr@k as logged.'),
           'env': ('conda tas: Python 3.10, torch 2.2.1+cu121, transformers 4.35.2, BLIP-2 OPT-2.7B (HF safetensors), '
                   'SAM ViT-H, CLIP ViT-B/32, spaCy 3.7 + en_core_web_trf, NLTK wordnet/punkt/averaged_perceptron_tagger; GPU1'),
           'metrics': {'mIoU': miou, 'oIoU': oiou, **prec},
           'notes': ('Full official RefCOCO val execution. Captions were generated by us with BLIP-2 (the repo does not ship '
                     'the per-sentence caption file); local fixes: HF Blip2Processor with use_fast=False because the released '
                     'tokenizer.json is not accepted by the fast tokenizer, and an empty non-synonym noun-chunk guard so the '
                     'negative-text term is dropped instead of launching a zero-batch CLIP kernel on CUDA. Log: ' + TAS_LOG),
           'log': TAS_LOG}
    json.dump(out, open(TAS_EVID, 'w'), indent=2)
    return out


def parse_t4s():
    if not os.path.exists(T4S_JSON):
        raise SystemExit('Text4Seg metrics json missing')
    m = json.load(open(T4S_JSON))
    if int(m.get('n') or 0) != 10834:
        raise SystemExit(f"Text4Seg n={m.get('n')} (expected 10834)")
    if m.get('mIoU') is None or m.get('cIoU') is None:
        raise SystemExit('Text4Seg metrics incomplete')
    out = {'method': 'Text4Seg (released llava-7b-p24 quick-inference checkpoint)', 'kind': 'method',
           'full_split': True, 'split': 'refcoco_val', 'n': int(m['n']),
           'protocol': m['protocol'], 'env': m['env'],
           'metrics': {'mIoU': float(m['mIoU']), 'cIoU': float(m['cIoU']),
                       'sam_mIoU': float(m['sam_mIoU']) if m.get('sam_mIoU') is not None else 0.0,
                       'sam_cIoU': float(m['sam_cIoU']) if m.get('sam_cIoU') is not None else 0.0},
           'notes': ('Full official RefCOCO val run with the released p24 checkpoint and SAM ViT-H refinement. '
                     'Local harness fixes required to execute the released code as intended: the repo calls the one-argument '
                     'translate_sequence that no longer exists (restored the official demo mapping), the SAM mask_input '
                     'variable was undefined (now the predicted low-res mask, matching model_semantic_seg.py), and '
                     'llava/eval/utils.py was missing torch/F imports. Generation was batched by image (group 8) as an '
                     'implementation detail; outputs were smoke-validated against the sequential path. '
                     'mIoU/cIoU are the generated-text masks; sam_* are the SAM-refined masks.'),
           'checkpoint': m.get('checkpoint', '')}
    json.dump(out, open(T4S_EVID, 'w'), indent=2)
    return out


def update(entry_key, out, entry, findings):
    d = json.load(open(DEEP))
    p = next(x for x in d['papers'] if x.get('key') == entry_key)
    c = p.setdefault('code', {})
    c['ran'] = True
    c['inspected'] = True
    if findings:
        c['findings'] = findings
    for k in ['blocker', 'blocker_evidence', 'retry_plan']:
        c.pop(k, None)
    c['run'] = entry
    json.dump(d, open(DEEP, 'w'), indent=2)


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else 'all'
    if which in ('tas', 'all'):
        out = parse_tas()
        entry = {'entry': 'python tas_main_hf.py --config config/refcoco/refcoco_val_run.yaml (official test path)',
                 'sample_n': out['n'], 'status': 'ok', 'kind': 'method', 'full_split': True,
                 'split': out['split'], 'protocol': out['protocol'], 'env': out['env'],
                 'datasets': {'refcoco_val': {'n': out['n'], 'metric': out['metrics']['mIoU']}},
                 'split_blockers': blockers(TAS_EVID), 'metrics': out['metrics'], 'notes': out['notes']}
        update('shu2023tas', out, entry,
               'TAS implements a training-free pipeline: SAM ViT-H automatic masks, BLIP-2 captions for crops, CLIP '
               'image/text scoring with spaCy noun-chunk heuristics and spatial rectification. The released entry point '
               'expects a per-sentence caption file; we generate it with BLIP-2 and run the official inference loop on '
               'the full RefCOCO val split.')
        print('recorded TAS', out['metrics'])
    if which in ('text4seg', 'all'):
        out = parse_t4s()
        entry = {'entry': 'python -m llava.eval.model_refer_seg_batched --dataset_split refcoco|unc|val (official Text4Seg harness)',
                 'sample_n': out['n'], 'status': 'ok', 'kind': 'method', 'full_split': True,
                 'split': out['split'], 'protocol': out['protocol'], 'env': out['env'],
                 'datasets': {'refcoco_val': {'n': out['n'], 'metric': out['metrics']['sam_mIoU']}},
                 'split_blockers': blockers(T4S_EVID), 'metrics': out['metrics'], 'notes': out['notes']}
        update('text4seg2024', out, entry,
               'llava/eval/model_refer_seg.py decodes the generated <seg> R-RLE text and refines the mask with SAM ViT-H; '
               'llava/eval/eval_refer_seg.py pools intersection/union over expressions (cIoU) and averages per-expression '
               'IoU (gIoU). The released quick-inference checkpoint is lmc22/text4seg-llava-7b-p24 on HuggingFace.')
        print('recorded Text4Seg', out['metrics'])


if __name__ == '__main__':
    main()
